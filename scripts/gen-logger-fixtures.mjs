// Generates the golden cases for the logger rules both apps share (apps/mini-app/src/logic/loggerOrder.ts):
//   test/fixtures/logger-order.json                                                          (golden cases)
//   mobile/shared/src/commonTest/kotlin/app/hacklimits/shared/workout/LoggerOrderFixturesGenerated.kt (embedded)
// Expectations are computed by the TS module, never written by hand; the Kotlin port
// (workout/logic/LoggerOrder.kt) is tested against them.
// Usage: npm run gen:logger-fixtures   (test/logger-order.test.ts fails while outputs are stale)
import { writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");

export const PATHS = {
  ts: join(ROOT, "apps/mini-app/src/logic/loggerOrder.ts"),
  jsonFixtures: join(ROOT, "test/fixtures/logger-order.json"),
  kotlinFixtures: join(ROOT, "mobile/shared/src/commonTest/kotlin/app/hacklimits/shared/workout/LoggerOrderFixturesGenerated.kt"),
};

// A fixed clock for the rest cases, so the fixtures don't change from run to run.
export const NOW = 1_800_000_000_000;
const DEFAULT_TARGET = 90;

// Every list length up to 4, every position (plus out-of-range ones), every focus (and none).
function listCases() {
  const cases = [];
  for (let length = 0; length <= 4; length++) {
    const focuses = [null, ...Array.from({ length }, (_, i) => i)];
    for (let at = -1; at <= length; at++) {
      for (const focus of focuses) cases.push({ length, at, focus });
    }
  }
  return cases;
}

const REST_INPUTS = [
  null,
  "not an object",
  {},
  { endAt: NOW + 60_000, startedAt: NOW - 30_000, target: 90, label: "Bench Press · set 2" },
  { endAt: NOW + 60_000, startedAt: NOW - 30_000 },
  { endAt: NOW + 60_000, startedAt: NOW - 30_000, target: 0, label: 5 },
  { endAt: NOW - 10_000, startedAt: NOW - 100_000, target: 90, label: "over 10s" },
  { endAt: NOW - 299_000, startedAt: NOW - 400_000, target: 90, label: "just under the cap" },
  { endAt: NOW - 300_000, startedAt: NOW - 400_000, target: 90, label: "at the cap" },
  { endAt: NOW + 60_000, startedAt: NOW + 120_000, target: 90, label: "started after its end" },
  { endAt: "soon", startedAt: NOW, target: 90, label: "" },
];

export async function buildArtifacts() {
  const m = await import(pathToFileURL(PATHS.ts).href);
  const lists = listCases();
  const move = [];
  for (const c of lists) {
    for (const direction of [-1, 1]) move.push({ ...c, direction, expected: m.moveInList(c.length, c.at, direction, c.focus) });
  }
  const remove = lists.map((c) => ({ ...c, expected: m.removeFromList(c.length, c.at, c.focus) }));
  const startsRest = [];
  for (const autoRest of [true, false]) {
    for (const wasDone of [true, false]) startsRest.push({ autoRest, wasDone, expected: m.startsRest(autoRest, wasDone) });
  }
  const resume = REST_INPUTS.map((saved) => ({ saved, expected: m.resumableRest(saved, NOW, DEFAULT_TARGET) }));
  const json = `${JSON.stringify({ source: "apps/mini-app/src/logic/loggerOrder.ts", now: NOW, defaultTarget: DEFAULT_TARGET, move, remove, startsRest, resume }, null, 1)}\n`;
  if (json.includes('"""')) throw new Error("fixtures cannot be a Kotlin raw string");
  const kotlin = [
    "// GENERATED by scripts/gen-logger-fixtures.mjs from test/fixtures/logger-order.json. Do not edit.",
    "// Regenerate with: npm run gen:logger-fixtures",
    "package app.hacklimits.shared.workout",
    "",
    `internal val LOGGER_ORDER_FIXTURES_JSON: String = """${json.replace(/\$/g, () => "${'$'}")}"""`,
    "",
  ].join("\n");
  return { json, kotlin };
}

// Line endings are normalized because git may check the files out with CRLF on Windows.
export function sameText(a, b) {
  return a.replace(/\r\n/g, "\n") === b.replace(/\r\n/g, "\n");
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { json, kotlin } = await buildArtifacts();
  writeFileSync(PATHS.jsonFixtures, json);
  writeFileSync(PATHS.kotlinFixtures, kotlin);
  console.log(`wrote ${PATHS.jsonFixtures}\nwrote ${PATHS.kotlinFixtures}`);
}
