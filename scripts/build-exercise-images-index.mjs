// Regenerates apps/mini-app/src/data/freeExerciseIds.ts from free-exercise-db (Unlicense,
// github.com/yuhonas/free-exercise-db): the ids of every non-stretching exercise, which are also
// its image folder names. Usage: node scripts/build-exercise-images-index.mjs [exercises.json]
// (without an argument it downloads dist/exercises.json at the pinned commit).
import { readFileSync, writeFileSync } from "node:fs";

export const FREE_EXERCISE_DB_COMMIT = "f00c92c7dcf1216a928a52c3706c7ce8e2f71ed5";
const src = process.argv[2];
const list = src
  ? JSON.parse(readFileSync(src, "utf8"))
  : await (await fetch(`https://raw.githubusercontent.com/yuhonas/free-exercise-db/${FREE_EXERCISE_DB_COMMIT}/dist/exercises.json`)).json();
const ids = list
  .filter((e) => e.category !== "stretching" && e.equipment !== "foam roll" && e.images?.length >= 1)
  .map((e) => e.id)
  .sort();
const out = `// Generated by scripts/build-exercise-images-index.mjs -- do not edit by hand.
// free-exercise-db (Unlicense) @ ${FREE_EXERCISE_DB_COMMIT}: ${ids.length} exercise ids (= image folders).
export const FREE_EXERCISE_DB_COMMIT = "${FREE_EXERCISE_DB_COMMIT}";
export const FREE_EXERCISE_IDS: string[] = ${JSON.stringify(ids)};
`;
writeFileSync(new URL("../apps/mini-app/src/data/freeExerciseIds.ts", import.meta.url), out);
console.log(`wrote ${ids.length} ids`);

// The exercise library (Mini App): each exercise's main muscle in the body map's vocabulary, its
// equipment and level, packed as "id|muscle|equipment|level" lines (~30 KB, loaded lazily).
const MUSCLE = {
  abdominals: "abs", abductors: "gluteal", adductors: "adductors", biceps: "biceps", calves: "calves", chest: "chest",
  forearms: "forearm", glutes: "gluteal", hamstrings: "hamstring", lats: "upper-back", "lower back": "lower-back",
  "middle back": "upper-back", neck: "neck", quadriceps: "quadriceps", shoulders: "deltoids", traps: "trapezius", triceps: "triceps",
};
const EQUIPMENT = {
  "body only": "body", dumbbell: "dumbbell", barbell: "barbell", kettlebells: "kettlebell", cable: "cable", machine: "machine",
  bands: "band", "e-z curl bar": "ezbar", "medicine ball": "ball", "exercise ball": "ball", other: "other",
};
const known = new Set(ids);
const rows = list
  .filter((e) => known.has(e.id))
  .map((e) => [e.id, MUSCLE[e.primaryMuscles?.[0]] ?? "other", EQUIPMENT[e.equipment] ?? "other", e.level === "beginner" ? "b" : e.level === "intermediate" ? "i" : "e"].join("|"))
  .sort();
writeFileSync(
  new URL("../apps/mini-app/src/data/freeExerciseLib.ts", import.meta.url),
  `// Generated by scripts/build-exercise-images-index.mjs -- do not edit by hand.
// free-exercise-db (Unlicense) @ ${FREE_EXERCISE_DB_COMMIT}: "id|muscle|equipment|level" per line
// (muscle in the body map's slugs, level b/i/e). The id's underscores are the English name.
export const FREE_EXERCISE_LIB = ${JSON.stringify(rows.join("\n"))};
`,
);
console.log(`wrote ${rows.length} library rows`);
